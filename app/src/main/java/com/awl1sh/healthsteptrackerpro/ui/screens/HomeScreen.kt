# HealthStepTrackerPro

A modern Android health and fitness app built with Kotlin and Jetpack Compose.

Features:
- Real-time step tracking with Android sensors
- Daily calorie and distance estimation
- Protein and nutrition tracking
- Hydration tracking with quick actions
- Daily goal monitoring
- User profile with weight, height, goal settings
- Clean dashboard, history, and settings UI

## Quick start
1. Open in Android Studio
2. Let Gradle sync
3. Run on a physical device or emulator

## Notes
Sensor availability varies by device. For best results, test on a real Android device with step counter support enabled.
